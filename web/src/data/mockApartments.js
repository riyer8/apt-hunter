const ago = (amount, unit) => {
  const ms = {
    minutes: 60 * 1000,
    hours: 60 * 60 * 1000,
    days: 24 * 60 * 60 * 1000,
  }[unit];
  return new Date(Date.now() - amount * ms).toISOString();
};

function listing(partial) {
  return {
    sources: [partial.source || "json"],
    evidence: {},
    previousPrice: null,
    confidence: CONFIDENCE.HIGH,
    ...partial,
  };
}

